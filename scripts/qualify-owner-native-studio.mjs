import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
import {fingerprintFiles} from './fingerprint-site-inputs.mjs';
const [manifestInput,studioInput,reportInput]=process.argv.slice(2);
if(!manifestInput||!studioInput||!reportInput)throw new Error('Pass absolute project manifest, Studio directory and report path');
const studio=path.resolve(studioInput),manifest=path.resolve(manifestInput),report=path.resolve(reportInput);process.env.TOADAL_PROJECT=manifest;
const fingerprint=()=>fingerprintFiles(path.dirname(manifest),['project.json','pages','games','assets','themes','collections','content','behaviors','plugins','animations','mechanics','variables']);
const sourceBefore=fingerprint();
const {createBridge}=await import(pathToFileURL(path.join(studio,'packages/ai-bridge/src/index.ts')));
const {createMcpProtocol}=await import(pathToFileURL(path.join(studio,'apps/mcp/protocol.ts')));
const protocol=createMcpProtocol(createBridge(manifest));
const response=await protocol.handle({jsonrpc:'2.0',id:1,method:'tools/call',params:{name:'toadal.qa',arguments:{level:'full'}}});
if(response.error||response.result?.isError)throw new Error('Full Studio QA failed: '+JSON.stringify(response));
const qa=response.result.structuredContent;
const doctor=spawnSync(process.execPath,['--no-warnings','--experimental-strip-types','scripts/ai-doctor.ts'],{cwd:studio,env:process.env,encoding:'utf8',maxBuffer:8*1024*1024});
const sourceAfter=fingerprint(),sourceUnchanged=JSON.stringify(sourceBefore)===JSON.stringify(sourceAfter);
const result={schema:'toadal-feast.owner-native-studio-qualification.v1',manifest,studio,node:process.version,qa,doctor:{exitCode:doctor.status,stdout:doctor.stdout,stderr:doctor.stderr},sourceBefore,sourceAfter,sourceUnchanged};
fs.mkdirSync(path.dirname(report),{recursive:true});fs.writeFileSync(report,JSON.stringify(result,null,2)+'\n');
const passed=sourceUnchanged&&doctor.status===0&&qa?.tests?.status===0&&qa?.validation?.valid===true&&qa?.graph?.dangling?.length===0&&qa?.accessibility?.errors===0;
console.log(JSON.stringify({report,qaStatus:passed?'PASS':'FAIL',sourceUnchanged,validation:qa?.validation,tests:qa?.tests?.status,doctorStatus:doctor.status,testSummary:qa?.tests?.stdout?.slice(-500)},null,2));
if(!passed)process.exitCode=1;
